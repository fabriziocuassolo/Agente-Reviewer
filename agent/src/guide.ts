import pc from "picocolors";

/**
 * Ayuda principal (`guardian`, `guardian --help`, `guardian help`).
 * Escrita para alguien que usa Guardian por primera vez y no programa:
 * qué es, cómo empezar, cada comando con ejemplos, cómo elegir la IA,
 * qué significan los resultados y qué hacer si algo falla.
 */

const t = (s: string) => pc.bold(pc.cyan(s)); // título de sección
const cmd = (s: string) => pc.green(s); // algo para escribir en la terminal
const dim = (s: string) => pc.dim(s);

export function mainGuide(): string {
  return [
    "",
    pc.bold("🛡  GUARDIAN · tu revisor de código automático"),
    "",
    "Guardian mira los cambios que hiciste en tu proyecto, busca errores (contraseñas",
    "escritas en el código, cálculos de precios mal hechos, problemas de seguridad...),",
    "te explica cada uno con cómo arreglarlo y decide si el cambio está listo:",
    `  ${pc.green("APROBADO")}      podés avanzar`,
    `  ${pc.yellow("ADVERTENCIA")}   podés avanzar, pero hay cosas para mirar`,
    `  ${pc.red("BLOQUEADO")}     corregí lo que dice antes de subir el cambio`,
    "",
    t("PRIMEROS PASOS"),
    `  1. Abrí la terminal dentro de la carpeta de tu proyecto (tiene que usar git).`,
    `  2. Hacé algún cambio en un archivo y guardalo.`,
    `  3. Escribí:  ${cmd("guardian review")}`,
    dim("     ¿Querés ver un ejemplo antes? Desde la carpeta de Guardian:  npm run demo -- all"),
    "",
    t("COMANDOS"),
    `  ${cmd("guardian review")}`,
    "      Revisa tus cambios y da el veredicto. Es el comando principal.",
    dim(`      Ej: guardian review --use ia`),
    "",
    `  ${cmd('guardian ask "tu pregunta"')}`,
    "      Le preguntás algo sobre el código y responde diciendo en qué archivo y línea está.",
    dim(`      Ej: guardian ask "¿dónde se calcula el envío?" --use local`),
    "",
    `  ${cmd('guardian dismiss <id> "motivo"')}`,
    "      Si Guardian marcó algo que en realidad está bien, lo descartás. Se acuerda y",
    "      no lo vuelve a marcar. El id aparece al lado de cada hallazgo (ej: G-4e781f).",
    dim(`      Ej: guardian dismiss G-4e781f "Es un dato de prueba, no una key real"`),
    "",
    `  ${cmd("guardian ia")}`,
    "      Muestra qué inteligencia artificial está usando y si cada opción está lista.",
    "",
    `  ${cmd("guardian install-hook")}   /   ${cmd("guardian uninstall-hook")}`,
    "      Activa (o quita) la revisión automática: cada vez que hagas git push, Guardian",
    "      revisa primero y, si está BLOQUEADO, no deja subir el cambio.",
    "",
    t("ELEGIR LA INTELIGENCIA ARTIFICIAL"),
    `  Agregá ${cmd("--use <opción>")} a review o ask. Si no ponés nada, usa replay.`,
    "",
    `  ${pc.bold("--use replay")}   ${dim("(por defecto)")}`,
    "      Respuestas reales de una IA, grabadas de antemano. No necesita nada: ni cuenta,",
    "      ni internet. Sirve SOLO para los ejemplos de la demo (npm run demo).",
    "",
    `  ${pc.bold("--use ia")}   ${dim('(o "--use gemini")')}   Gemini de Google, en la nube`,
    "      La más precisa. Necesita una clave gratuita (API key):",
    "        1. Entrá a https://aistudio.google.com/apikey y tocá \"Create API key\".",
    "        2. Abrí el archivo .env de la carpeta de Guardian y pegala así:",
    `           ${cmd("GEMINI_API_KEY=tu-clave")}`,
    "      Límite gratis: unas 20 revisiones por día.",
    `      ${pc.yellow("Ojo:")} tu código se envía a Google. Con código de una empresa, mejor la local.`,
    "",
    `  ${pc.bold("--use local")}   ${dim('(o "--use ollama")')}   IA en tu propia computadora`,
    "      Privada: el código nunca sale de tu máquina. Gratis y sin límite. Se instala una vez:",
    `        1. Instalá Ollama:   ${cmd("winget install Ollama.Ollama")}   (o https://ollama.com/download)`,
    `        2. Abrí la app Ollama y descargá el modelo:   ${cmd("ollama pull qwen2.5-coder:7b")}`,
    "      Menos precisa que Gemini. Si tu placa de video tiene 12 GB o más, usá el modelo",
    `      más grande:  ${cmd("ollama pull qwen2.5-coder:14b")}  y después  ${cmd("--model qwen2.5-coder:14b")}`,
    "",
    "  Si elegís una que todavía no configuraste, Guardian te dice exactamente qué falta.",
    `  Para cambiar la opción por defecto: ${cmd("LLM_PROVIDER=replay")} | gemini | ollama  en el archivo .env`,
    "",
    t("OPCIONES ÚTILES DE guardian review"),
    `  ${cmd("--use <ia>")}        Qué IA usar: replay, ia (Gemini) o local (Ollama).`,
    `  ${cmd("--model <nombre>")}  Qué modelo de esa IA (ej: qwen2.5-coder:14b, gemini-3.8-flash).`,
    `  ${cmd("--no-llm")}          Sin IA: solo los controles automáticos (rápido, gratis, sin internet).`,
    `  ${cmd("--base <rama>")}     Comparar contra otra rama (por defecto, contra la principal).`,
    `  ${cmd("--json")}            Resultado en formato para otros programas (ej: GitHub).`,
    `  ${cmd("--record")}          Graba las respuestas de la IA para usarlas después con replay.`,
    "",
    t("CÓMO LEER EL RESULTADO"),
    "  Chequeos determinísticos   Controles automáticos que siempre dan lo mismo: claves escritas",
    "                             en el código, estilo (ESLint), tipos (TypeScript) y tests.",
    "  Hallazgos                  Cada problema con su archivo:línea, explicación y una flecha →",
    "                             con la sugerencia para arreglarlo.",
    `  Gravedad                   ${pc.red("CRÍTICO")} rompe dinero, datos o seguridad · ${pc.red("ALTO")} error probable`,
    `                             ${pc.yellow("MEDIO")} riesgo moderado · ${pc.cyan("BAJO")} mejora menor`,
    "  Decisión                   El veredicto y qué regla lo decidió (ej: 1 crítico → BLOQUEADO).",
    "",
    t("SI ALGO NO FUNCIONA"),
    `  "guardian no se reconoce"     En la carpeta de Guardian corré:  ${cmd("npm install")}  y  ${cmd("npm link")}`,
    `  "no está dentro de un repositorio git"   Abrí la terminal en la carpeta de tu proyecto.`,
    `  "No hay cambios para revisar" ¿Guardaste el archivo? Guardian revisa lo que cambió.`,
    `  Gemini respondió 429           Se terminó el cupo gratis del día: probá ${cmd("--use local")}.`,
    `  Gemini respondió 503           Google está saturado: esperá un minuto o usá ${cmd("--use local")}.`,
    `  "No encuentro Ollama"          Abrí la app Ollama (o corré ${cmd("ollama serve")}).`,
    "",
    t("MÁS AYUDA"),
    `  ${cmd("guardian <comando> --help")}   Detalle y ejemplos de un comando (ej: guardian review --help)`,
    "  README.md y docs/TUTORIAL.md      Guía paso a paso, en la carpeta de Guardian",
    "",
  ].join("\n");
}

