/** `guardian ayuda otra-ia`: cómo agregar cualquier IA (gratis o paga) desde el .env. */
export function otherAIGuide(envPath: string): string {
  const v = (s: string) => pc.yellow(s); // línea para copiar al .env
  return [
    "",
    pc.bold("🧩  AGREGAR OTRA IA A GUARDIAN"),
    "",
    "Guardian puede usar casi cualquier IA: ChatGPT, Claude, DeepSeek, Groq, Mistral, OpenRouter,",
    "o un modelo propio. No hace falta programar: se agrega escribiendo 3 líneas en el archivo .env.",
    "",
    t("ANTES DE EMPEZAR: SUSCRIPCIÓN ≠ API"),
    "  Pagar ChatGPT Plus o Claude Pro NO alcanza: eso es para usar el chat en la web.",
    "  Guardian necesita una CLAVE DE API (API key), que se saca en la consola para",
    "  desarrolladores del proveedor y se paga aparte, según cuánto se usa (por \"tokens\").",
    "  Una revisión típica usa entre 5.000 y 12.000 tokens: suele costar centavos de dólar.",
    "",
    t("PASO 1 · Conseguí la clave (API key) de tu proveedor"),
    "  ChatGPT (OpenAI)   https://platform.openai.com/api-keys",
    "  Claude (Anthropic) https://console.anthropic.com/settings/keys",
    "  DeepSeek           https://platform.deepseek.com/api_keys",
    "  Groq               https://console.groq.com/keys",
    "  Mistral            https://console.mistral.ai/api-keys",
    "  OpenRouter         https://openrouter.ai/keys     (una sola clave para cientos de modelos)",
    "",
    t("PASO 2 · Abrí el archivo .env de Guardian"),
    `  Está en: ${envPath}`,
    "  (si no existe, copiá .env.example con ese nombre). Abrilo con cualquier editor de texto.",
    "",
    t("PASO 3 · Elegí un nombre y escribí 3 líneas"),
    "  El nombre es el que después vas a usar en --use (solo letras, números y guión bajo).",
    "  Las líneas siempre empiezan con IA_ + el nombre en MAYÚSCULAS:",
    "",
    `    ${v("IA_NOMBRE_URL=")}     dirección de la API del proveedor (ver tabla abajo)`,
    `    ${v("IA_NOMBRE_KEY=")}     tu clave del paso 1`,
    `    ${v("IA_NOMBRE_MODEL=")}   el modelo que quieras usar`,
    "",
    "  Ejemplo con ChatGPT (el nombre elegido es \"chatgpt\"):",
    `    ${v("IA_CHATGPT_URL=https://api.openai.com/v1")}`,
    `    ${v("IA_CHATGPT_KEY=tu-clave")}`,
    `    ${v("IA_CHATGPT_MODEL=nombre-del-modelo")}   ${dim("← lista en https://platform.openai.com/docs/models")}`,
    "",
    "  Ejemplo con Claude: lleva una línea más, porque Claude usa su propio formato",
    "  (y no necesita URL):",
    `    ${v("IA_CLAUDE_FORMATO=anthropic")}`,
    `    ${v("IA_CLAUDE_KEY=tu-clave")}`,
    `    ${v("IA_CLAUDE_MODEL=claude-opus-5-5")}   ${dim("← o claude-sonnet-5-5 / claude-haiku-5-5 (más barato)")}`,
    "",
    t("DIRECCIÓN (URL) DE CADA PROVEEDOR"),
    "  ChatGPT (OpenAI)  https://api.openai.com/v1",
    "  DeepSeek          https://api.deepseek.com          modelo: deepseek-chat",
    "  Groq              https://api.groq.com/openai/v1",
    "  Mistral           https://api.mistral.ai/v1",
    "  OpenRouter        https://openrouter.ai/api/v1",
    "  LM Studio (local) http://localhost:1234/v1          sin clave: dejá la línea KEY afuera",
    "  Ollama (local)    mejor usá --use local: ya viene incluido y ajusta la memoria del modelo",
    "  Claude            no lleva URL: usá IA_<NOMBRE>_FORMATO=anthropic",
    dim("  Cualquier otro servicio que diga \"compatible con OpenAI\" también funciona: usá su URL."),
    "",
    t("PASO 4 · Comprobá que Guardian la reconoce"),
    `  ${cmd("guardian ia")}   tu IA aparece en la lista con ✔ si está completa (o te dice qué falta)`,
    "",
    t("PASO 5 · Usala"),
    `  ${cmd("guardian review --use chatgpt")}`,
    `  ${cmd('guardian ask "¿dónde se calcula el envío?" --use claude')}`,
    `  ${cmd("guardian review --use chatgpt --model otro-modelo")}   probar otro modelo sin editar el .env`,
    "",
    "  ¿Querés que sea la IA por defecto? En el .env cambiá:",
    `    ${v("LLM_PROVIDER=chatgpt")}`,
    "",
    t("OTRAS FORMAS DE CARGAR LA CLAVE (sin escribirla en el archivo)"),
    "  Solo para la terminal actual:",
    `    PowerShell:   ${cmd('$env:IA_CHATGPT_KEY="tu-clave"')}`,
    `    Mac / Linux:  ${cmd('export IA_CHATGPT_KEY="tu-clave"')}`,
    "  Permanente en Windows (abrí una terminal nueva después):",
    `    ${cmd('setx IA_CHATGPT_KEY "tu-clave"')}`,
    "  En GitHub Actions: Settings → Secrets and variables → Actions → New repository secret,",
    "  y en el workflow pasala como variable de entorno (env: IA_CHATGPT_KEY: ${{ secrets.IA_CHATGPT_KEY }}).",
    "",
    t("CUIDADOS"),
    "  · La clave es como una contraseña: no la compartas ni la subas a GitHub",
    "    (el .env ya está excluido de git).",
    "  · Las IAs pagas cobran por uso: en la consola del proveedor podés poner un límite de gasto.",
    "  · Tu código se envía a ese proveedor: revisá su política de datos antes de usarlo con código",
    "    de una empresa. Guardian igual tapa las claves y contraseñas que encuentre antes de enviar.",
    `  · No se pueden usar los nombres reservados: replay, gemini, ia, ollama, local.`,
    "",
    t("SI ALGO FALLA"),
    "  \"respondió 401\" o \"403\"   La clave está mal copiada o no tiene permisos.",
    "  \"respondió 404\"          Revisá la URL y el nombre exacto del modelo.",
    "  \"respondió 429\"          Límite de uso o falta saldo en la cuenta del proveedor.",
    "  \"No conozco la IA\"       El nombre en --use no coincide con el de las líneas IA_..._",
    "",
  ].join("\n");
}

